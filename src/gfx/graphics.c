void gfx_putchar(uint32_t x, uint32_t y, char ch, uint32_t color) {
	if (ch < 32 || ch > 126)
		ch = '?';
	const uint8_t* glyph = _font[ch - 32];

	for (uint32_t row = 0; row < 8; row++) {
		uint8_t bits = glyph[row];
		for (uint32_t col = 0; col < 8; col++) {
			if (bits & (1 << col)) {
				for (uint32_t dy = 0; dy < 2; dy++) {
					for (uint32_t dx = 0; dx < 2; dx++) {
						uint32_t px = x + col * 2 + dx;
						uint32_t py = y + row * 2 + dy;

						gInfo->fb.data[py * gInfo->fb.pitch + px] = color;
					}
				}
			}
		}
	}
}

void gfx_puttext(uint32_t x, uint32_t y, const char* text, uint32_t color) {
	uint32_t startX = x;

	for (const char* p = text; *p; p++) {
		char ch = *p;

		if (ch == '\n') {
			y += 16;
			x = startX;
			continue;
		}

		if (ch == '\t') {
			x += 64;
			continue;
		}

		gfx_putchar(x, y, ch, color);

		x += 16;
	}
}