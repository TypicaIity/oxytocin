#include "graphics.h"

extern BootInfo* gInfo;

void gfx_clear(uint32_t color) {
	for (uint64_t i = 0; i < gInfo->fb.height; i++) {
		for (uint64_t j = 0; j < gInfo->fb.width; j++)
			gInfo->fb.data[i * gInfo->fb.pitch + j] = color;
	}
}

void gfx_putpixel(uint32_t x, uint32_t y, uint32_t color) {
	gInfo->fb.data[y * gInfo->fb.pitch + x] = color;
}

void gfx_putrect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color) {
	uint32_t endX = x + w, endY = y + h;
	for (uint32_t y1 = y; y1 < endY; y1++) {
		for (uint32_t x1 = x; x1 < endX; x1++)
			gInfo->fb.data[y1 * gInfo->fb.pitch + x1] = color;
	}
}

static int abs(int x) {
	return x > 0 ? x : x * -1;
}

void gfx_putline(uint32_t x0, uint32_t y0, uint32_t x1, uint32_t y1, uint32_t color) {
	int dx = abs((int)x1 - (int)x0), dy = abs((int)y1 - (int)y0);
	int sx = (x0 < x1) ? 1 : -1, sy = (y0 < y1) ? 1 : -1;

	int err = dx - dy;
	while (true) {
		gInfo->fb.data[y1 * gInfo->fb.pitch + x0] = color;

		if (x0 == x1 && y0 == y1)
			break;

		int e2 = 2 * err;
		if (e2 > -dy)
			err -= dy, x0 += sx;
		if (e2 < dx)
			err += dx, y0 += sy;
	}
}

void gfx_putcircle(uint32_t cx, uint32_t cy, uint32_t radius, uint32_t color) {
	int x = 0, y = radius;
	int d = 3 - 2 *  radius;

	while (y >= x) {
		gInfo->fb.data[(cy + x) * gInfo->fb.pitch + (cx + y)] = color;
		gInfo->fb.data[(cy - x) * gInfo->fb.pitch + (cx + y)] = color;
		gInfo->fb.data[(cy + x) * gInfo->fb.pitch + (cx - y)] = color;
		gInfo->fb.data[(cy - x) * gInfo->fb.pitch + (cx - y)] = color;
		gInfo->fb.data[(cy + y) * gInfo->fb.pitch + (cx + x)] = color;
		gInfo->fb.data[(cy - y) * gInfo->fb.pitch + (cx + x)] = color;
		gInfo->fb.data[(cy + y) * gInfo->fb.pitch + (cx - x)] = color;
		gInfo->fb.data[(cy - y) * gInfo->fb.pitch + (cx - x)] = color;

		x++;

		if (d > 0)
			y--, d = d + 4 * (x - y) + 10;
		else
			d = d + 4 * x + 6;
	}
}

void gfx_putfilledcircle(uint32_t cx, uint32_t cy, uint32_t radius, uint32_t color) {
	int x = radius, y = 0, err = 1 - x;

	while (x >= y) {
		for (uint32_t i = cx - x; i <= cx + x; i++)
			gInfo->fb.data[(cy + y) * gInfo->fb.pitch + i] = color;
		if (y != 0)
			for (uint32_t i = cx - x; i <= cx + x; i++)
				gInfo->fb.data[(cy - y) * gInfo->fb.pitch + i] = color;

		for (uint32_t i = cx - y; i <= cx + y; i++)
			gInfo->fb.data[(cy + x) * gInfo->fb.pitch + i] = color;
		if (x != y)
			for (uint32_t i = cx - y; i <= cx + y; i++)
				gInfo->fb.data[(cy - x) * gInfo->fb.pitch + i] = color;

		y++;
		if (err < 0)
			err += 2 * y + 1;
		else
			x--, err += 2 * (y - x) + 1;
	}
}

